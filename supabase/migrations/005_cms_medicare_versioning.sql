What's New in the Database

Over the weekend, we crawled and ingested two major new sources — CMS.gov and Medicare.gov — which means the IRMAA and Medicare data is now substantially more complete. Here's a summary of what's now in the system:

SSA POMS — 16,850 documents
CMS.gov — 9,741 HTML pages + 11,023 PDF documents
Medicare.gov — 404 pages
Code of Federal Regulations (CFR) — 2,004 documents
All of that has been processed into 1,106,824 searchable indexed passages that AXIOM can draw from when answering questions. Questions about Medicare Part B premiums, IRMAA surcharges, appeals processes, and CMS coverage rules should now be answered with much greater accuracy and depth.

